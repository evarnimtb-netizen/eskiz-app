"""Draws the 1280x640 social preview banner for the GitHub repository.

Everything is drawn in code from the Eskiz icon (packaging/icons/png, itself generated by
packaging/icon-gen) and the bundled Atkinson Hyperlegible Next font (OFL).

    python3 packaging/social/make_banner.py        # needs Pillow; writes social-preview.png
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(__file__).with_name("social-preview.png")
W, H = 1280, 640

# Colours from the v5 icon spec: navy background gradient, blueprint ink, nib gradient.
NAVY_TOP = (0x26, 0x32, 0x4A)
NAVY_BOTTOM = (0x0B, 0x10, 0x20)
BLUEPRINT = (0x8F, 0xB9, 0xF2)
INK = (0xEA, 0xF4, 0xFF)
NIB = [(0xFF, 0xB2, 0x24), (0xFF, 0x5A, 0x1F), (0xF0, 0x12, 0x4B), (0xE0, 0x39, 0x9E)]


def lerp(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def vertical_gradient(size, top, bottom):
    w, h = size
    img = Image.new("RGB", size)
    draw = ImageDraw.Draw(img)
    for y in range(h):
        draw.line([(0, y), (w, y)], fill=lerp(top, bottom, y / (h - 1)))
    return img


def nib_bar(width, height):
    """A horizontal bar with the nib's four-stop gradient."""
    bar = Image.new("RGB", (width, height))
    draw = ImageDraw.Draw(bar)
    stops = len(NIB) - 1
    for x in range(width):
        t = x / (width - 1) * stops
        i = min(int(t), stops - 1)
        draw.line([(x, 0), (x, height)], fill=lerp(NIB[i], NIB[i + 1], t - i))
    return bar


def blueprint_grid(img):
    """Faint blueprint grid with a dash-dot corner bracket, echoing the icon."""
    grid = Image.new("RGBA", img.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(grid)
    for x in range(0, W, 40):
        draw.line([(x, 0), (x, H)], fill=BLUEPRINT + (14,))
    for y in range(0, H, 40):
        draw.line([(0, y), (W, y)], fill=BLUEPRINT + (14,))
    # Corner bracket at the top right, dash-dot like the icon's construction line.
    x0, y0, length = W - 72, 56, 150
    for start in range(0, length, 26):
        draw.line([(x0 - start, y0), (x0 - min(start + 16, length), y0)], fill=BLUEPRINT + (120,), width=3)
        draw.line([(x0, y0 + start), (x0, y0 + min(start + 16, length))], fill=BLUEPRINT + (120,), width=3)
    img.alpha_composite(grid)


def main():
    img = vertical_gradient((W, H), NAVY_TOP, NAVY_BOTTOM).convert("RGBA")

    # Soft vignette glow behind the icon.
    glow = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ImageDraw.Draw(glow).ellipse([60, 120, 520, 580], fill=(0x3A, 0x4A, 0x6E, 150))
    img.alpha_composite(glow.filter(ImageFilter.GaussianBlur(80)))
    blueprint_grid(img)

    # The macOS-grid icon (transparent margin and soft shadow are part of the artwork).
    icon = Image.open(ROOT / "icons/png/eskiz-macos-512.png").convert("RGBA").resize((400, 400), Image.LANCZOS)
    img.alpha_composite(icon, (90, 120))

    fonts = ROOT / "identity/fonts"
    title = ImageFont.truetype(str(fonts / "AtkinsonHyperlegibleNext-SemiBold.ttf"), 132)
    body = ImageFont.truetype(str(fonts / "AtkinsonHyperlegibleNext-Regular.ttf"), 38)
    small = ImageFont.truetype(str(fonts / "AtkinsonHyperlegibleNext-Regular.ttf"), 28)

    draw = ImageDraw.Draw(img)
    x = 560
    draw.text((x, 150), "Eskiz", font=title, fill=INK)
    img.paste(nib_bar(220, 8), (x + 6, 310))
    draw.text((x, 348), "A free painting app for every screen.", font=body, fill=INK)
    draw.text((x, 398), "No account. Your files stay yours.", font=body, fill=(0xC9, 0xD6, 0xEA))
    draw.text((x, 478), "macOS  ·  Windows  ·  Linux  ·  Android preview", font=small, fill=BLUEPRINT)
    draw.text((x, 518), "Open source (MIT or Apache-2.0)", font=small, fill=BLUEPRINT)

    img.convert("RGB").save(OUT, optimize=True)
    print(f"wrote {OUT} ({W}x{H})")


if __name__ == "__main__":
    main()
