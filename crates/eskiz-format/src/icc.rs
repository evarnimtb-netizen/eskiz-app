//! ICC profiles for the colour spaces Eskiz documents use, generated in code.
//!
//! Nothing here is copied from a third-party profile. [`profile`] builds a version 2.1
//! matrix/TRC display profile (class `mntr`, colour space `RGB `, PCS `XYZ `) from the published
//! primaries and D65 white point in `eskiz_guides::colour_space`, which is what the ICC
//! specification asks of such a profile:
//!
//! * `rXYZ`, `gXYZ`, `bXYZ` are the columns of the linear-RGB-to-XYZ matrix, adapted from D65 to the
//!   D50 profile connection space with the Bradford transform, and `chad` holds that adaptation;
//! * `wtpt` is D50 and `rTRC`, `gTRC`, `bTRC` share one 1024-entry `curv` table of the sRGB
//!   transfer function, which both sRGB and Display P3 use (version 2 has no parametric curve);
//! * `desc` carries [`ColourSpace::profile_name`] and `cprt` a short licence statement.
//!
//! The output is deterministic: the date in the header is fixed, so identical documents export
//! identical bytes.
//!
//! Licence: the profiles are produced by this code and dedicated to the public domain (CC0), so they
//! can be embedded in any export without attribution.

use eskiz_guides::colour_space::{
    decode_transfer, mat_inv, mat_mul, rgb_to_xyz_matrix, ColourSpace, Matrix3, D65, DISPLAY_P3_PRIMARIES,
    SRGB_PRIMARIES,
};

/// D50, the ICC profile connection space white, as XYZ with Y = 1.
const D50: [f64; 3] = [0.9642, 1.0, 0.8249];
/// Bradford cone response matrix.
const BRADFORD: Matrix3 = [
    [0.8951, 0.2664, -0.1614],
    [-0.7502, 1.7135, 0.0367],
    [0.0389, -0.0685, 1.0296],
];
/// Entries in the shared transfer curve.
const CURVE_ENTRIES: usize = 1024;

fn s15f16(v: f64) -> [u8; 4] {
    ((v * 65536.0).round() as i32).to_be_bytes()
}

/// Bradford adaptation from the D65 white point to D50.
fn d65_to_d50() -> Matrix3 {
    let d65 = [D65.0 / D65.1, 1.0, (1.0 - D65.0 - D65.1) / D65.1];
    let cone = |w: [f64; 3]| -> [f64; 3] { std::array::from_fn(|i| (0..3).map(|k| BRADFORD[i][k] * w[k]).sum()) };
    let (src, dst) = (cone(d65), cone(D50));
    let scale: Matrix3 = std::array::from_fn(|i| std::array::from_fn(|j| if i == j { dst[i] / src[i] } else { 0.0 }));
    mat_mul(&mat_inv(&BRADFORD), &mat_mul(&scale, &BRADFORD))
}

fn primaries(space: ColourSpace) -> [(f64, f64); 3] {
    match space {
        ColourSpace::Srgb => SRGB_PRIMARIES,
        ColourSpace::DisplayP3 => DISPLAY_P3_PRIMARIES,
    }
}

fn xyz_tag(v: [f64; 3]) -> Vec<u8> {
    let mut t = b"XYZ \0\0\0\0".to_vec();
    for c in v {
        t.extend(s15f16(c));
    }
    t
}

fn text_tag(text: &str) -> Vec<u8> {
    let mut t = b"text\0\0\0\0".to_vec();
    t.extend(text.as_bytes());
    t.push(0);
    t
}

/// A version 2 `textDescriptionType` with an ASCII description and empty Unicode and ScriptCode parts.
fn desc_tag(text: &str) -> Vec<u8> {
    let mut t = b"desc\0\0\0\0".to_vec();
    t.extend(((text.len() + 1) as u32).to_be_bytes());
    t.extend(text.as_bytes());
    t.push(0);
    t.extend([0u8; 4 + 4]); // Unicode language code and count
    t.extend([0u8; 2 + 1 + 67]); // ScriptCode code, count and 67 bytes of text
    t
}

fn curve_tag() -> Vec<u8> {
    let mut t = b"curv\0\0\0\0".to_vec();
    t.extend((CURVE_ENTRIES as u32).to_be_bytes());
    for i in 0..CURVE_ENTRIES {
        let linear = decode_transfer(i as f64 / (CURVE_ENTRIES - 1) as f64);
        t.extend(((linear * 65535.0).round() as u16).to_be_bytes());
    }
    t
}

fn chad_tag(m: &Matrix3) -> Vec<u8> {
    let mut t = b"sf32\0\0\0\0".to_vec();
    for row in m {
        for v in row {
            t.extend(s15f16(*v));
        }
    }
    t
}

/// The ICC profile for `space`, as the bytes of a `.icc` file.
pub fn profile(space: ColourSpace) -> Vec<u8> {
    let adapt = d65_to_d50();
    let to_xyz = mat_mul(&adapt, &rgb_to_xyz_matrix(primaries(space), D65));
    let column = |c: usize| [to_xyz[0][c], to_xyz[1][c], to_xyz[2][c]];
    let curve = curve_tag();

    // Tags, in the order they are stored. The three curves share one block.
    let blocks: Vec<(&[u8; 4], Vec<u8>)> = vec![
        (b"desc", desc_tag(space.profile_name())),
        (b"cprt", text_tag("Generated by Eskiz from published primaries. CC0 / public domain.")),
        (b"wtpt", xyz_tag(D50)),
        (b"rXYZ", xyz_tag(column(0))),
        (b"gXYZ", xyz_tag(column(1))),
        (b"bXYZ", xyz_tag(column(2))),
        (b"chad", chad_tag(&adapt)),
        (b"rTRC", curve),
    ];
    let tag_count = blocks.len() + 2; // gTRC and bTRC point at rTRC's block
    let table_len = 4 + tag_count * 12;
    let mut offset = 128 + table_len;
    let mut table = Vec::with_capacity(table_len);
    table.extend((tag_count as u32).to_be_bytes());
    let mut body = Vec::new();
    let mut curve_at = (0usize, 0usize);
    for (sig, data) in &blocks {
        let size = data.len();
        table.extend(sig.iter());
        table.extend((offset as u32).to_be_bytes());
        table.extend((size as u32).to_be_bytes());
        if *sig == b"rTRC" {
            curve_at = (offset, size);
        }
        body.extend(data.iter());
        while body.len() % 4 != 0 {
            body.push(0);
        }
        offset = 128 + table_len + body.len();
    }
    for sig in [b"gTRC", b"bTRC"] {
        table.extend(sig.iter());
        table.extend((curve_at.0 as u32).to_be_bytes());
        table.extend((curve_at.1 as u32).to_be_bytes());
    }

    let total = 128 + table.len() + body.len();
    let mut h = Vec::with_capacity(128);
    h.extend((total as u32).to_be_bytes());
    h.extend([0u8; 4]); // preferred CMM: none
    h.extend([2, 0x10, 0, 0]); // version 2.1.0
    h.extend(b"mntr");
    h.extend(b"RGB ");
    h.extend(b"XYZ ");
    for field in [2024u16, 1, 1, 0, 0, 0] {
        h.extend(field.to_be_bytes()); // creation date, fixed for reproducible output
    }
    h.extend(b"acsp");
    h.extend([0u8; 4 + 4 + 4 + 4 + 8]); // platform, flags, manufacturer, model, attributes
    h.extend([0u8; 4]); // rendering intent: perceptual
    for v in D50 {
        h.extend(s15f16(v)); // illuminant
    }
    h.resize(128, 0); // creator, profile ID and reserved bytes
    let mut out = h;
    out.extend(table);
    out.extend(body);
    out
}

/// The tag data of `sig` in a profile, if the profile has it.
fn tag<'a>(profile: &'a [u8], sig: &[u8; 4]) -> Option<&'a [u8]> {
    if profile.len() < 132 || &profile[36..40] != b"acsp" {
        return None;
    }
    let count = u32::from_be_bytes(profile[128..132].try_into().ok()?) as usize;
    for i in 0..count.min(256) {
        let e = profile.get(132 + i * 12..144 + i * 12)?;
        if &e[..4] == sig {
            let off = u32::from_be_bytes(e[4..8].try_into().ok()?) as usize;
            let len = u32::from_be_bytes(e[8..12].try_into().ok()?) as usize;
            return profile.get(off..off.checked_add(len)?);
        }
    }
    None
}

/// The profile's description (`desc` tag, ASCII part), if it has one.
pub fn description(profile: &[u8]) -> Option<String> {
    let d = tag(profile, b"desc")?;
    if d.len() < 12 || &d[..4] != b"desc" {
        // A version 4 profile uses multiLocalizedUnicode; the name is not needed for those.
        return None;
    }
    let n = u32::from_be_bytes(d[8..12].try_into().ok()?) as usize;
    let text = d.get(12..12 + n)?;
    Some(String::from_utf8_lossy(text.split(|&b| b == 0).next()?).into_owned())
}

/// Which Eskiz colour space an embedded profile stands for, judging by its description and, when
/// that is missing, by the red colorant. `None` for a profile that is not an RGB display profile.
pub fn space_of_profile(profile: &[u8]) -> Option<ColourSpace> {
    if profile.len() < 132 || &profile[16..20] != b"RGB " {
        return None;
    }
    if let Some(name) = description(profile) {
        return Some(ColourSpace::from_profile_name(&name));
    }
    // Display P3's red colorant has X above 0.5 in D50 (sRGB's is 0.4360).
    let red = tag(profile, b"rXYZ")?;
    let x = i32::from_be_bytes(red.get(8..12)?.try_into().ok()?);
    Some(if f64::from(x) / 65536.0 > 0.5 { ColourSpace::DisplayP3 } else { ColourSpace::Srgb })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn xyz(profile: &[u8], sig: &[u8; 4]) -> [f64; 3] {
        let t = tag(profile, sig).expect("tag");
        std::array::from_fn(|i| f64::from(i32::from_be_bytes(t[8 + i * 4..12 + i * 4].try_into().unwrap())) / 65536.0)
    }

    #[test]
    fn profiles_are_well_formed() {
        for space in ColourSpace::ALL {
            let p = profile(space);
            assert_eq!(u32::from_be_bytes(p[0..4].try_into().unwrap()) as usize, p.len());
            assert_eq!(p.len() % 4, 0);
            assert_eq!(&p[12..16], b"mntr");
            assert_eq!(&p[36..40], b"acsp");
            assert_eq!(description(&p).as_deref(), Some(space.profile_name()));
            assert_eq!(space_of_profile(&p), Some(space));
            assert_eq!(profile(space), p, "deterministic");
        }
    }

    #[test]
    fn srgb_colorants_match_the_published_d50_values() {
        // The sRGB profile in the ICC registry has these colorants (rounded to 4 places).
        let p = profile(ColourSpace::Srgb);
        let (r, g, b) = (xyz(&p, b"rXYZ"), xyz(&p, b"gXYZ"), xyz(&p, b"bXYZ"));
        let near = |a: [f64; 3], e: [f64; 3]| a.iter().zip(e).all(|(x, y)| (x - y).abs() < 2e-4);
        assert!(near(r, [0.4360, 0.2225, 0.0139]), "{r:?}");
        assert!(near(g, [0.3851, 0.7169, 0.0971]), "{g:?}");
        assert!(near(b, [0.1431, 0.0606, 0.7141]), "{b:?}");
    }

    #[test]
    fn display_p3_colorants_sum_to_the_d50_white() {
        let p = profile(ColourSpace::DisplayP3);
        let (r, g, b) = (xyz(&p, b"rXYZ"), xyz(&p, b"gXYZ"), xyz(&p, b"bXYZ"));
        for i in 0..3 {
            assert!((r[i] + g[i] + b[i] - D50[i]).abs() < 2e-4, "channel {i}");
        }
        // Display P3 red is more saturated than sRGB red.
        assert!(r[0] > 0.51 && r[0] < 0.52, "{r:?}");
    }

    #[test]
    fn the_curve_is_the_srgb_transfer_function() {
        let p = profile(ColourSpace::Srgb);
        let c = tag(&p, b"rTRC").expect("curve");
        assert_eq!(u32::from_be_bytes(c[8..12].try_into().unwrap()) as usize, CURVE_ENTRIES);
        let at = |i: usize| f64::from(u16::from_be_bytes(c[12 + i * 2..14 + i * 2].try_into().unwrap())) / 65535.0;
        assert_eq!(at(0), 0.0);
        assert_eq!(at(CURVE_ENTRIES - 1), 1.0);
        assert!((at(512) - decode_transfer(512.0 / 1023.0)).abs() < 1e-4);
        assert_eq!(tag(&p, b"gTRC"), tag(&p, b"rTRC"));
    }
}
